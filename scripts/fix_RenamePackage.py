#!/usr/bin/env python3
"""
Rename the application package inside a baksmali output tree.

Run with cwd = the baksmali output directory (same convention as the other
scripts/fix_*.py fixers).

Three passes:

  A. Type descriptors -- `Lcom/autonavi/amapauto/` -> `Lcom/autonavi/amapautolite/`
     ALWAYS, everywhere.  The 13 classes that live in that package are physically
     moved, so every reference to them must follow, including references that
     appear inside methods whose *string literals* we deliberately keep.

  B. String literals -- `"com.autonavi.amapauto"` / `"com.autonavi.amapauto.<x>"`
     renamed, EXCEPT inside the KEEP sites listed below.  Those are the values
     that are reported to the Amap / BYD backend (account binding, arrival-data
     upload, TTS-to-car messaging) plus the BYD `syncpatch` appId and the car's
     package-installer `format` marker.  Renaming them would change what the
     server sees, so -- per the agreed "conservative" scope -- they stay.

  C. Directory move -- the `com/autonavi/amapauto/` package directories become
     `com/autonavi/amapautolite/`.

Pass B deliberately DOES rewrite the AIDL interface tokens
(`com.autonavi.amapauto.aidl.IJsonProtocol*`).  Those strings are generated by
the AIDL compiler as `<package>.<interface>`; keeping them in sync with the
renamed interface classes preserves the generated-code invariant.  Both ends of
those Binder interfaces live inside this APK, so no external peer is affected.
"""
import os
import re
import shutil
import sys

OLD = 'com.autonavi.amapauto'
NEW = 'com.autonavi.amapautolite'

# ContentProvider authorities that are NOT derived from the package name.  Two of
# them collide head-on with the car's pre-installed app and make installation fail
# with INSTALL_FAILED_CONFLICTING_PROVIDER (surfaced by the BYD installer as
# "与现有软件冲突"):
#
#   com.byd.naviauto.mapprovider  (com.autosdk.drive.magspace.MagSpaceContentProvider)
#   com.byd.automap.fenceprovider (com.autosdk.bussiness.geofence.FenceContentProvider)
#
# Both are exported BYD integration endpoints.  Renaming ours leaves the
# pre-installed app as the endpoint the rest of the head unit talks to, while our
# side-by-side copy gets a private authority.  Each authority also names a
# <permission> element, so the prefix replacement covers those too.
EXTRA = [
    ('com.byd.naviauto.mapprovider', 'com.autonavi.amapautolite.mapprovider'),
    ('com.byd.automap.fenceprovider', 'com.autonavi.amapautolite.fenceprovider'),
]
OLD_DESC = 'Lcom/autonavi/amapauto/'
NEW_DESC = 'Lcom/autonavi/amapautolite/'

# NEW starts with OLD ("com.autonavi.amapauto" + "lite"), so a plain str.replace
# would rewrite its own output on a second pass.  Anchor the package match with a
# negative lookahead for the already-renamed tail.
OLD_RE = re.compile(re.escape(OLD) + r'(?!lite)')

# (path substring, None = whole file, else list of .method signatures to skip)
KEEP = [
    # ---- reported to the Amap/BYD backend as "who is asking" ----
    ('com/byd/automap/receiver/BydAccountReceiver$CallBackNotify.smali', None),
    ('com/byd/automap/receiver/BydAccountReceiver.smali',
     ['lambda$onReceive$0()V', 'lambda$onReceive$1()V',
      'unBindRequest(Ljava/lang/String;Ljava/lang/String;)V']),
    ('com/autonavi/amapauto/protocol/service/JsonProtocolService.smali', None),
    ('com/autosdk/common/settings/ProtocolUtils.smali', None),
    ('com/autosdk/bussiness/utils/AesDemoUtil.smali', None),
    ('k/e/g/d2/b/h.smali', None),
    ('com/autosdk/settings/presenter/SettingAssetPresenter.smali', None),
    ('com/autosdk/user/presenter/account/', None),
    # ---- BYD platform integration / external protocol markers ----
    ('com/byd/carmodel/CarModelPackageManager.smali', None),
    ('com/byd/automap/application/AutoApplication.smali', None),
]

# Binder interface tokens generated by the AIDL compiler as `<package>.<interface>`.
# They must follow the renamed interface classes or the generated proxy/stub pair
# stops matching and every call throws "Binder invocation to an incorrect
# interface".  So they are renamed unconditionally, even inside a KEEP file.
ALWAYS_RENAME = ('com.autonavi.amapauto.aidl.',)

METHOD_RE = re.compile(r'^\.method\b.*$')
STR_RE = re.compile(r'^(?P<ind>[ \t]*)const-string(?:/jumbo)?[ \t]+(?P<reg>[^,]+),[ \t]*"(?P<val>[^"]*)"[ \t]*$')
# `.field public static final AUTHORITY:Ljava/lang/String; = "com.example"` -- a string
# literal that is a field initialiser, not a const-string instruction.
FIELD_STR_RE = re.compile(r'^(?P<head>[ \t]*\.field\b[^=]*=)[ \t]*"(?P<val>[^"]*)"[ \t]*$')


def keep_for(rel):
    """Return (whole_file_kept: bool, set_of_kept_methods)."""
    for pat, methods in KEEP:
        if pat in rel:
            if methods is None:
                return True, set()
            return False, set(methods)
    return False, set()


def rename_strings(text, kept_methods, keep_all=False):
    """Pass B on one file body.  Returns (text, renamed, kept)."""
    if not text:
        return text, 0, 0
    out = []
    cur_name = None
    n = 0
    kept = 0
    for line in text.split('\n'):
        if METHOD_RE.match(line):
            # `.method public static synthetic lambda$onReceive$0()V` -> `lambda$onReceive$0()V`
            cur_name = line.split()[-1]
        m = STR_RE.match(line) or FIELD_STR_RE.match(line)
        if m:
            val = m.group('val')
            # Non-package-derived authorities (always renamed, never kept).
            for a, b in EXTRA:
                val = val.replace(a, b)
            # Package name, anchored so it cannot re-match its own output.
            if OLD_RE.search(val):
                always = any(k in val for k in ALWAYS_RENAME)
                if not always and (keep_all or (cur_name is not None and any(cur_name.endswith(k) for k in kept_methods))):
                    kept += 1
                else:
                    val = OLD_RE.sub(NEW, val)
            if val != m.group('val'):
                if 'reg' in m.groupdict():
                    line = '%sconst-string %s, "%s"' % (m.group('ind'), m.group('reg'), val)
                else:
                    line = '%s "%s"' % (m.group('head'), val)
                n += 1
        out.append(line)
    return '\n'.join(out), n, kept


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else '.'
    if not any(os.path.isdir(os.path.join(root, d)) for d in os.listdir(root) if d.startswith('smali')):
        sys.exit('no smali* directory in %s' % os.path.abspath(root))

    files = []
    for dp, dn, fn in os.walk(root):
        for f in fn:
            if f.endswith('.smali'):
                files.append(os.path.join(dp, f))

    desc_total = 0
    str_total = 0
    kept_total = 0
    moved = 0
    kept_report = {}

    for p in files:
        rel = os.path.relpath(p, root)
        kept_file, kept_methods = keep_for(rel)
        txt = open(p, encoding='utf-8').read()
        orig = txt

        # Pass A -- type descriptors, unconditional
        d = txt.count(OLD_DESC)
        if d:
            txt = txt.replace(OLD_DESC, NEW_DESC)
            desc_total += d

        # Pass B -- string literals, honouring KEEP (ALWAYS_RENAME still applies)
        txt, n, k = rename_strings(txt, kept_methods, keep_all=kept_file)
        str_total += n
        if k:
            kept_report[rel] = kept_report.get(rel, 0) + k
            kept_total += k

        if txt != orig:
            with open(p, 'w', encoding='utf-8') as fh:
                fh.write(txt)

    print('[rename] string literals kept (reported to server / BYD markers):')
    for rel, c in sorted(kept_report.items()):
        print('    %-90s %d' % (rel, c))

    # Pass C -- move the package directories
    for d in sorted(os.listdir(root)):
        if not d.startswith('smali'):
            continue
        src = os.path.join(root, d, 'com', 'autonavi', 'amapauto')
        if os.path.isdir(src):
            dst = os.path.join(root, d, 'com', 'autonavi', 'amapautolite')
            if os.path.exists(dst):
                shutil.rmtree(dst)
            shutil.move(src, dst)
            moved += 1
            print('  moved %s -> %s' % (src, dst))

    print('[rename] %s -> %s' % (OLD, NEW))
    print('[rename] type descriptors rewritten : %d' % desc_total)
    print('[rename] string literals rewritten  : %d' % str_total)
    print('[rename] string literals kept       : %d' % kept_total)
    print('[rename] package dirs moved         : %d' % moved)

    # post-conditions -- soft by default because this fixer is also run on dexes
    # that do not contain the package at all (it is then simply a no-op).
    strict = '--strict' in sys.argv
    leftover = [os.path.join(dp, f) for dp, dn, fn in os.walk(root) for f in fn
                if f.endswith('.smali')
                and OLD_DESC in open(os.path.join(dp, f), encoding='utf-8').read()]
    if leftover:
        sys.exit('leftover old type descriptor in: %s' % leftover[:5])
    if strict:
        assert desc_total > 0, 'no type descriptors renamed'
        assert str_total > 0, 'no string literals renamed'
        assert moved > 0, 'no package directory moved'


if __name__ == '__main__':
    main()
